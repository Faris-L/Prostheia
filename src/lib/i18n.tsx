export function translateInterfaceCopy(locale: Locale, text: string): string {
  return locale === "sr" ? interfaceCopySr[text] ?? text : text;
}

export const INTERFACE_COPY_KEYS = Object.keys(interfaceCopySr);

export function useInterfaceCopy() {
  const { locale } = useI18n();
  return useCallback((text: string) => translateInterfaceCopy(locale, text), [locale]);
}

type I18nValue = { locale: Locale; setLocale: (locale: Locale) => void; t: (key: MessageKey) => string };
const I18nContext = createContext<I18nValue | null>(null);
const LOCALE_CHANGE_EVENT = "prostheia:locale-change";
let volatileLocale: Locale = DEFAULT_LOCALE;

function subscribeToLocale(onChange: () => void) {
  window.addEventListener("storage", onChange);
  window.addEventListener(LOCALE_CHANGE_EVENT, onChange);
  return () => {
    window.removeEventListener("storage", onChange);
    window.removeEventListener(LOCALE_CHANGE_EVENT, onChange);
  };
}

function getLocaleSnapshot(): Locale {
  try {
    const stored = window.localStorage.getItem(LOCALE_STORAGE_KEY);
    return stored === null ? volatileLocale : resolveLocale(stored);
  } catch { return volatileLocale; }
}

function getServerLocaleSnapshot() { return DEFAULT_LOCALE; }

export function I18nProvider({ children }: { children: ReactNode }) {
  const locale = useSyncExternalStore(subscribeToLocale, getLocaleSnapshot, getServerLocaleSnapshot);
  useEffect(() => {
    document.documentElement.lang = locale;
    usePracticeSessionStore.getState().setLocale(locale);
  }, [locale]);
  const setLocale = useCallback((value: Locale) => {
    const next = resolveLocale(value);
    volatileLocale = next;
    usePracticeSessionStore.getState().setLocale(next);
    try { window.localStorage.setItem(LOCALE_STORAGE_KEY, next); } catch { /* The selection still applies for this session. */ }
    window.dispatchEvent(new Event(LOCALE_CHANGE_EVENT));
  }, []);
  const value = useMemo(() => ({ locale, setLocale, t: (key: MessageKey) => translate(locale, key) }), [locale, setLocale]);
  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>;
}

export function useI18n() {
  const value = useContext(I18nContext);
  if (!value) throw new Error("useI18n must be used inside I18nProvider");
  return value;
}

export function formatNumber(value: number, locale: Locale, maximumFractionDigits = 2) {
  return new Intl.NumberFormat(locale === "sr" ? "sr-Latn-RS" : "en-US", { maximumFractionDigits }).format(value);
}

